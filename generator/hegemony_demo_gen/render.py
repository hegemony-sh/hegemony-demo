def login_table(model: Model) -> str:
    width = max(len(p.username) for p in model.personas)
    lines = [
        f"{model.operator} demo logins (http://localhost:8080)",
        "",
        "Every user has the same password, generated on your machine by install.sh.",
        "Read it with: task password   (or: cat deploy/compose/.local/demo.env)",
        "",
    ]
    for persona in model.personas:
        lines.append(f"  {persona.username.ljust(width)}  {persona.persona:<9} {persona.about}")
    return "\n".join(lines) + "\n"


def demo_env(model: Model) -> str:
    users = " ".join(p.username for p in model.personas)
    lines = [
        _header(model).rstrip("\n"),
        "# Read by deploy/compose/compose.sh as a second --env-file.",
        f'KEYCLOAK_IMPORTED_USERS="{users}"',
    ]
    return "\n".join(lines) + "\n"



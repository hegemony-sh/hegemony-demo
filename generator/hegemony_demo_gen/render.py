# The Configuration Exchange schema the bundles target (platform 1.0.0).
BUNDLE_SCHEMA_VERSION = 3
# The lab's Gitea repository the git inventory provider reads planned sites from.
INVENTORY_REPOSITORY_NAME = "lab-inventory"
# Where the lab's Gitea seed puts the pinned inventory inside that repository.
INVENTORY_PATH = "inventory"

# Fixed, published demo credentials of the lab (see lab.py).
ROUTER_USERNAME, ROUTER_PASSWORD = labmod.OPERATOR_LOGIN
TENANT_DEVICE_USERNAME, TENANT_DEVICE_PASSWORD = labmod.TENANT_LOGIN

GENERATED_NOTE = "Generated by demo-gen from spec/{spec}.yaml. Do not edit; edit the spec."


class _Dumper(yaml.SafeDumper):
    """Block-style YAML, no anchors, multi-line strings as literal blocks."""

    def ignore_aliases(self, data: Any) -> bool:
        return True


def _str_representer(dumper: yaml.SafeDumper, data: str) -> yaml.ScalarNode:
    if "\n" in data:
        return dumper.represent_scalar("tag:yaml.org,2002:str", data, style="|")
    return dumper.represent_scalar("tag:yaml.org,2002:str", data)


_Dumper.add_representer(str, _str_representer)


def dump_yaml(data: Any) -> str:
    return yaml.dump(data, Dumper=_Dumper, sort_keys=False, allow_unicode=True, width=100, indent=2)


def dump_json(data: Any) -> str:
    return json.dumps(data, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def secret_ref(org: str, folder: str, key: str) -> str:
    return "{{ secret('vault://orgs/" + org + "/secrets/" + folder + "/" + key + "') }}"


def ssh_access(org: str, folder: str) -> dict[str, Any]:
    return {
        "ssh": {
            "username_ref": secret_ref(org, folder, "username"),
            "password_ref": secret_ref(org, folder, "password"),
        }
    }


def _header(model: Model) -> str:
    return "# " + GENERATED_NOTE.format(spec=model.spec_id) + "\n"


# --------------------------------------------------------------------------- bundles


def org_directory(model: Model) -> dict[str, Any]:
    organizations = []
    for org in model.orgs:
        entry: dict[str, Any] = {
            "slug": org.slug,
            "name": org.name,
            "description": org.description,
            "is_active": True,
        }
        if org.shared:
            entry["is_shared"] = True
        entry["idp_mappings"] = [
            {"claim": "groups", "value": group, "role": roles[org.slug]}
            for group, roles in model.groups.items()
            if org.slug in roles
        ]
        organizations.append(entry)
    return {"schema_version": BUNDLE_SCHEMA_VERSION, "organizations": organizations}


def site_record(model: Model, code: str) -> dict[str, Any]:
    site = next(s for s in model.sites if s.code == code)
    org = model.org(site.org)
    return {
        "name": site.name,
        "description": f"{site.group.capitalize()} site {site.code} of {org.name}.",
        "location": f"{org.region or ''}, {model.region_root}".strip(", "),
        "tags": {"code": site.code, "group": site.group, "status": site.status},
    }


def device_attributes(device: Device) -> dict[str, Any]:
    attributes: dict[str, Any] = {
        "vendor": device.vendor,
        "model": device.model,
        "serial": device.serial,
        "loopback": device.loopback,
    }
    if device.live:
        attributes["simulated"] = True
    return attributes


def device_record(model: Model, device: Device, login_path: str) -> dict[str, Any]:
    site = next(s for s in model.sites if s.code == device.site)
    return {
        "name": device.name,
        "mgmt_host": device.mgmt_host,
        "platform": device.platform,
        "site": site.name,
        "attributes": device_attributes(device),
        "access_config": ssh_access(device.org, login_path),
        "tags": {"role": device.role, "site": device.site, "status": site.status},
    }


def org_bundle(model: Model, org: Org, stories: StoryOutput) -> dict[str, Any]:
    bundle: dict[str, Any] = {"schema_version": BUNDLE_SCHEMA_VERSION, "organization": org.slug}
    devices = model.devices_of(org.slug, source="bundle")

    secrets: list[dict[str, Any]] = []
    login_path = ""
    if org.slug == "default" and devices:
        login_path = "ops/device/ssh"
        secrets.append(
            {
                "name": "ops-device-ssh",
                "description": (
                    "DEMO ONLY: SSH login of the operator's devices and simulated routers."
                ),
                "folder": f"orgs/{org.slug}/secrets/{login_path}",
                "values": {"username": ROUTER_USERNAME, "password": ROUTER_PASSWORD},
            }
        )
    elif devices:
        login_path = "netops/device/ssh"
        secrets.append(
            {
                "name": "netops-device-ssh",
                "description": "DEMO ONLY: SSH login of this organization's devices.",
                "folder": f"orgs/{org.slug}/secrets/{login_path}",
                "values": {"username": TENANT_DEVICE_USERNAME, "password": TENANT_DEVICE_PASSWORD},
            }
        )
    if org.slug == "default":
        secrets.append(
            {
                "name": "lab-git-login",
                "description": "DEMO ONLY: login of the lab's Gitea, for configuration backups.",
                "folder": f"orgs/{org.slug}/secrets/ops/git/https",
                "values": dict(zip(("username", "password"), labmod.GIT_LOGIN, strict=True)),
            }
        )
    if secrets:
        bundle["secrets"] = secrets

    sites = [s.code for s in model.sites_of(org.slug) if s.source == "bundle"]
    if sites:
        bundle["sites"] = [site_record(model, code) for code in sites]
    if devices:
        bundle["devices"] = [device_record(model, d, login_path) for d in devices]

    git_sites = [s for s in model.sites_of(org.slug) if s.source == "git"]
    if git_sites:
        bundle["git_repositories"] = [
            {
                "name": INVENTORY_REPOSITORY_NAME,
                "url": labmod.git_url(labmod.GIT_INVENTORY_REPO),
                "branch": "main",
                # Plain HTTP to a private address: the lab's Gitea, on the lab's
                # own network. A real repository would use HTTPS.
                "allow_insecure_url": True,
                "sync_stale_seconds": 300,
            }
        ]
        bundle["inventory_providers"] = [
            {
                "name": "planned-sites",
                "provider_type": "git",
                "enabled": True,
                "description": (
                    "Planned sites and the service catalogue, read from the lab's Gitea "
                    "inventory repository."
                    if model.catalog.enabled
                    else "Planned sites, read from the lab's Gitea inventory repository."
                ),
                "config": {
                    "git_repository": INVENTORY_REPOSITORY_NAME,
                    "branch": "main",
                    "path": INVENTORY_PATH,
                    "query_cache_ttl_seconds": 60,
                },
            }
        ]

    variables = dict(org.variables)
    if not org.shared:
        variables.setdefault("ORG_NAME", org.name)
    if org.slug in model.contacts:
        contact = model.contacts[org.slug]
        variables.setdefault("NOC_CONTACT", model.email(contact.mailbox, org.slug))
    if variables:
        bundle["variables"] = [
            {"name": name, "value": value, "description": _variable_description(org, name)}
            for name, value in sorted(variables.items())
        ]

    destinations = stories.destinations.get(org.slug, [])
    if destinations:
        bundle["notification_destinations"] = destinations
    for section in ("flows", "flow_attachments", "flow_subscriptions", "schedules"):
        items = getattr(stories, section).get(org.slug, [])
        if items:
            bundle[section] = items
    return bundle


def _variable_description(org: Org, name: str) -> str:
    if org.shared:
        return f"Shared standard, inherited by every organization unless it sets {name} itself."
    if name == "ORG_NAME":
        return "Display name stamped into this organization's reports."
    if name == "NOC_CONTACT":
        return "Mailbox that receives this organization's notifications."
    return f"{org.name} sets its own {name}; it overrides the shared standard."



def inventory_documents(model: Model) -> dict[str, dict[str, Any] | None]:
    """The lab's Git inventory, keyed by path under the inventory root.

    The demo does not write these: the lab seeds its Gitea from a pinned tag of
    the inventory repository (platform.env). `demo-gen --check-inventory`
    compares a checkout of that tag with them. None is an empty `.gitkeep`.
    """
    documents: dict[str, dict[str, Any] | None] = {}
    for site in model.sites:
        if site.source != "git":
            continue
        org = model.org(site.org)
        documents[f"sites/{site.code}/{site.code}.yaml"] = {
            "schema_version": 1,
            "kind": "site",
            "external_id": site.code,
            "name": site.name,
            "description": f"{site.group.capitalize()} site of {org.name}, {site.status}.",
            "location": f"{org.region or ''}, {model.region_root}".strip(", "),
            "tags": {"group": site.group, "status": site.status},
        }
        for device in model.devices:
            if device.site != site.code:
                continue
            documents[f"devices/{device.name}.yaml"] = {
                "schema_version": 1,
                "kind": "device",
                "external_id": device.name,
                "name": device.name,
                "mgmt_host": device.mgmt_host,
                "platform": device.platform,
                "attributes": device_attributes(device),
                "site": site.code,
                "role": device.role,
                "tags": [device.role, site.status],
            }
    documents.update(catalog_files(model.catalog))
    return documents


def _same(actual: Any, expected: Any) -> bool:
    """Equal as data, type for type: `1` is not `true`, and `1.0` is not `1`.

    Mappings compare by key, whatever their order; lists compare item by item.
    """
    if type(actual) is not type(expected):
        return False
    if isinstance(expected, dict):
        return actual.keys() == expected.keys() and all(
            _same(actual[key], value) for key, value in expected.items()
        )
    if isinstance(expected, list):
        return len(actual) == len(expected) and all(
            _same(a, e) for a, e in zip(actual, expected, strict=True)
        )
    return actual == expected


def check_inventory(model: Model, tree: Path) -> list[str]:
    """What differs between an inventory tree and what the spec expects.

    Records are compared as data, so the inventory repository may carry its own
    comments and formatting. Any other file under the tree is reported too: the
    Git inventory plugin reads everything there.
    """
    expected = inventory_documents(model)
    if not tree.is_dir():
        return [f"missing: {tree}"]
    found = {p.relative_to(tree).as_posix() for p in tree.rglob("*") if p.is_file()}
    problems: list[str] = []
    for path, document in sorted(expected.items()):
        target = tree / path
        if path not in found:
            problems.append(f"missing: {path}")
        elif document is not None:
            try:
                actual = yaml.safe_load(target.read_text(encoding="utf-8"))
            except (yaml.YAMLError, OSError, UnicodeError) as exc:
                problems.append(f"unreadable: {path}: {exc}")
                continue
            if not _same(actual, document):
                problems.append(f"differs: {path}")
    problems.extend(f"extra:   {p}" for p in sorted(found - set(expected)))
    return problems


# --------------------------------------------------------------------------- docs


def cast_table(model: Model) -> str:
    lines = [
        "<!-- " + GENERATED_NOTE.format(spec=model.spec_id) + " -->",
        "",
        "| Login | Persona | Role | Organizations |",
        "| --- | --- | --- | --- |",
    ]
    names = {o.slug: o.name for o in model.orgs}
    for persona in model.personas:
        reach: dict[str, str] = {}
        for group in persona.groups:
            for org_slug, role in model.groups[group].items():
                reach.setdefault(org_slug, role)
        orgs = ", ".join(f"{names[s]} ({r})" for s, r in reach.items())
        lines.append(f"| `{persona.username}` | {persona.persona} | {persona.role} | {orgs} |")
    return "\n".join(lines) + "\n"


def sites_table(model: Model) -> str:
    lines = [
        "<!-- " + GENERATED_NOTE.format(spec=model.spec_id) + " -->",
        "",
        "| Site | Code | Organization | Type | Status | Devices | Inventory |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for site in model.sites:
        devices = [d for d in model.devices if d.site == site.code]
        names = ", ".join(f"`{d.name}`" + (" (live)" if d.live else "") for d in devices)
        source = "Git" if site.source == "git" else "bundle"
        lines.append(
            f"| {site.name} | `{site.code}` | {model.org(site.org).name} | {site.group} "
            f"| {site.status} | {names} | {source} |"
        )
    return "\n".join(lines) + "\n"


def summary(model: Model) -> dict[str, Any]:
    return {
        "spec": model.spec_id,
        "organizations": len(model.orgs),
        "users": len(model.personas),
        "sites": len(model.sites),
        "devices": len(model.devices),
        "live_devices": len(model.live_devices()),
        "lab_routers": len(model.lab.routers()),
        "lab_servers": len(model.lab.servers()),
        "stories": [s.id for s in model.stories],
    }


# --------------------------------------------------------------------------- all


def render_all(model: Model, stories_root: Any) -> dict[str, str]:
    """Every output file, keyed by its path relative to the repository root."""
    stories = render_stories(model, stories_root)
    files: dict[str, str] = {}
    head = _header(model)
    files["dist/bundles/00-organizations.yaml"] = head + dump_yaml(org_directory(model))
    for number, org in enumerate(model.orgs, start=1):
        files[f"dist/bundles/{number * 10:02d}-{org.slug}.yaml"] = head + dump_yaml(
            org_bundle(model, org, stories)
        )
    files["dist/keycloak/realm.json"] = dump_json(keycloak_realm(model))
    files["dist/logins.txt"] = login_table(model)
    files["dist/demo.env"] = demo_env(model)
    files["dist/lab/compose.yml"] = head + dump_yaml(labmod.compose(model))
    files["dist/lab/checks.txt"] = labmod.checks(model, GENERATED_NOTE.format(spec=model.spec_id))
    for node in model.lab.routers():
        files[f"dist/lab/frr/{node.name}.conf"] = labmod.frr_config(model.lab, node)
    files["docs/_generated/topology.md"] = labmod.topology_page(
        model, GENERATED_NOTE.format(spec=model.spec_id)
    )
    files["docs/_generated/cast.md"] = cast_table(model)
    files["docs/_generated/sites.md"] = sites_table(model)
    files["dist/summary.json"] = dump_json(summary(model))
    manifest = {
        path: hashlib.sha256(text.encode()).hexdigest()
        for path, text in sorted(files.items())
        if path.startswith("dist/")
    }
    files["dist/MANIFEST.json"] = dump_json({"files": manifest})
    return files
